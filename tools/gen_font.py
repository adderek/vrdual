#!/usr/bin/env python3
# Bakes printable ASCII of a monospace TTF into common/vrdual_font.hpp
# (4-bit coverage, one hex digit per pixel) for the vrdual-xr overlay.
# Needs ImageMagick. Run once; the output is committed:
#   python3 tools/gen_font.py /usr/share/fonts/TTF/DejaVuSansMono.ttf 24 > common/vrdual_font.hpp
import subprocess
import sys

font, size = sys.argv[1], sys.argv[2]
glyphs, W, H = [], None, None
for code in range(32, 127):
    ch = chr(code)
    # label:@file avoids ImageMagick's own escapes ('%', '@', '\')
    out = subprocess.run(["magick", "-background", "black", "-fill", "white", "-font", font, "-pointsize", size,
                          "label:@-", "-depth", "8", "gray:-"], input=ch.encode(), capture_output=True, check=True).stdout
    dim = subprocess.run(["magick", "-background", "black", "-fill", "white", "-font", font, "-pointsize", size,
                          "label:@-", "-format", "%w %h", "info:"], input=ch.encode(), capture_output=True, check=True).stdout.split()
    w, h = int(dim[0]), int(dim[1])
    if W is None:
        W, H = w, h
    assert (w, h) == (W, H), (ch, w, h)
    glyphs.append("".join("%x" % (b >> 4) for b in out))

print("// Generated by tools/gen_font.py from %s at %s pt: do not edit." % (font.rsplit("/", 1)[-1], size))
print("// Printable ASCII 32..126, %dx%d px, 4-bit coverage, one hex digit per pixel, rows top down." % (W, H))
print("#pragma once")
print("namespace vrdual {")
print("constexpr int kFontW = %d, kFontH = %d;" % (W, H))
print("static const char* const kFont[95] = {")
for g in glyphs:
    print('    "%s",' % g)
print("};")
print("}  // namespace vrdual")
